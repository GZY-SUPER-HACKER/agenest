"""What the agent is told about the registered machines — as a file, and as a tool.

Two renderings of one truth, and the split is deliberate (docs/design.md §24):

- **The file** (`MACHINES.registered.md`, written into the agent's workspace) is the standing
  answer: which hosts exist, which of them the user has authorized, and the exact `ssh` line for
  each one. It is rewritten whenever the registry or an approval changes, and it is *not* in the
  prompt — the per-turn appendix carries one index line pointing at it, so a fleet of hosts
  costs the context nothing until the agent asks.
- **The tool output** (`csd_registry`, through `pi/registry.ts`) is the live answer, for the one
  question a file cannot answer: what is running *now*. It reads the database read-only on the
  agent's own machine, so there is no token to hand out and no endpoint to secure.

Neither ever contains key material. The `ssh` line names the private key's *path*; the file the
agent would need to read is on its own filesystem, mode 0600, and stays there.
"""

from __future__ import annotations

import argparse
import logging
import sys
from datetime import datetime, timezone
from pathlib import Path

from ..database import Database
from ..schemas import SessionStatus
from ..services import host_access_service as ha
from ..services import session_service as ss

logger = logging.getLogger("csd.hosts.view")

#: The generated file's name, kept beside this module's job so the two cannot drift.
REGISTRY_FILE = "MACHINES.registered.md"

#: What the file says about itself, first, because the reader might be the agent or a person.
FILE_HEADER = """\
# Registered coding agents

Generated by the coding-session dashboard. **Do not edit** — it is rewritten whenever a host
registers or an access approval changes. `MACHINES.md` beside it is the operator's own notes and
is never touched by this file.

A host is here because its connector reported itself. That is **not** access: the user authorizes
each host separately, and only a host marked `ready` below may be driven. Everything here is a
report about another machine — the address in particular is the one the user approved, and this
dashboard has not verified that it is reachable from here.
"""

_ACCESS_LINES = {
    "ready": "ready — approved by the user",
    "pending": "waiting — the key is generated; the host installs it on its next heartbeat",
    "requested": (
        "not authorized — tell the user, who authorizes it in Settings → Host access. "
        "Do not guess credentials or addresses."
    ),
    "address_changed": (
        "the host is declaring a different address than it did when this was approved, so the "
        "old command is void. Ask the user to re-approve it."
    ),
    "disabled": "revoked by the user",
}


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _age(stamp: str | None) -> str:
    """`3m ago` / `2h ago`, or `?` when the timestamp is missing.

    Relative rather than absolute for the tool, where the reader is a model with no clock of
    its own: "connected, last report 4m ago" is a fact it can use, an ISO string it cannot.
    """
    if not stamp:
        return "?"
    try:
        when = ss.parse_ts(stamp)
    except (TypeError, ValueError):
        return "?"
    seconds = (_now() - when).total_seconds()
    if seconds < 90:
        return "just now"
    if seconds < 3600:
        return f"{int(seconds // 60)}m ago"
    if seconds < 86400:
        return f"{int(seconds // 3600)}h ago"
    return f"{int(seconds // 86400)}d ago"


def _hosts_and_access(db: Database) -> list[tuple]:
    """Every host with its access row, newest report first — the order the rail uses.

    Two queries and a join in Python rather than a SQL join: a host without an approval is the
    common case, and an inner join would silently drop exactly those rows.
    """
    hosts = db.query("SELECT * FROM agent_hosts ORDER BY last_seen_at DESC")
    access = {row["host_id"]: row for row in db.query("SELECT * FROM host_access")}
    return [(host, access.get(host["id"])) for host in hosts]


def _state(host_row, access_row):
    return ha.state_for(host_row, access_row)


def _ssh_line(host_row, access_row) -> str | None:
    """The command the agent runs, or `None` when there is nothing it may run.

    Built from the *approved* address and the key on this machine — never from the connector's
    declaration, which is the whole point of keeping the two apart.
    """
    if access_row is None or access_row["state"] == ha.DISABLED:
        return None
    return (
        f"ssh -i {access_row['key_path']} -p {access_row['ssh_port']} "
        f"{access_row['ssh_user']}@{access_row['ssh_host']}"
    )


def render_markdown(db: Database, *, stale_after_seconds: int = 900) -> str:
    """The whole generated file."""
    parts = [FILE_HEADER]
    rows = _hosts_and_access(db)
    if not rows:
        parts.append(
            "Nothing has registered yet. A machine appears here the first time its connector "
            "reports itself (`csd-agent install`, then a heartbeat).\n"
        )
        return "\n".join(parts)

    for host_row, access_row in rows:
        state = _state(host_row, access_row)
        lines = [f"## {host_row['label']} — {host_row['agent_type']}", ""]

        seen = f"last reported {_age(host_row['last_seen_at'])}"
        if host_row["disconnected_at"]:
            seen = f"said goodbye {_age(host_row['disconnected_at'])}"
        elif _maybe_stale(host_row, stale_after_seconds):
            seen = f"possibly offline — last reported {_age(host_row['last_seen_at'])}"
        lines.append(f"connected since {host_row['connected_at']} · {seen}")

        declared = _declared_text(host_row)
        if declared:
            lines.append(f"the host declares it is reachable at {declared}")

        label = _ACCESS_LINES.get(state or "", "not requested")
        if state == "ready" and access_row is not None and access_row["installed_at"]:
            label = f"{label} on {access_row['installed_at']}"
        lines.append(f"access: {label}")
        if access_row is not None and access_row["last_error"]:
            lines.append(f"last install attempt failed: {access_row['last_error']}")

        command = _ssh_line(host_row, access_row)
        if command and state == "ready":
            lines += [
                "",
                "    " + command,
                "",
                "Full shell is allowed: drive the coding agent the way its user would, e.g.",
                f"`{command} 'cd <repo> && claude -p \"…\"'`.",
            ]
        elif command:
            # The command exists but is not usable yet. Showing it invites the agent to try it
            # anyway, so it is named as pending rather than printed.
            lines += [
                "",
                "A key is on file but not usable yet (`access:` above says why). Wait for the "
                "host's next heartbeat rather than trying the command.",
            ]
        lines.append("")
        parts.append("\n".join(lines))

    return "\n".join(parts).rstrip() + "\n"


def _declared_text(host_row) -> str | None:
    declared = ha.declared_for(host_row)
    if declared == (None, None, None):
        return None
    host, user, port = declared
    return f"{user or '?'}@{host or '?'}:{port or 22}"


def _maybe_stale(host_row, stale_after_seconds: int) -> bool:
    """The same hint the rail computes, without the threshold plumbing.

    The file is a snapshot, so "possibly offline" here is only ever approximate — which is why
    it is worded as a possibility and why the live answer is the tool's job.
    """
    if host_row["disconnected_at"]:
        return False
    try:
        quiet = (_now() - ss.parse_ts(host_row["last_seen_at"])).total_seconds()
    except (TypeError, ValueError):
        return False
    return quiet >= stale_after_seconds


def render_tool_text(
    db: Database,
    *,
    action: str = "hosts",
    host: str | None = None,
    limit: int = 50,
    stale_after_seconds: int = 900,
) -> str:
    """The live answer `csd_registry` returns."""
    if action == "sessions":
        return _render_sessions(
            db, host=host, limit=limit, stale_after_seconds=stale_after_seconds
        )
    return _render_hosts(db, stale_after_seconds=stale_after_seconds)


def _render_hosts(db: Database, *, stale_after_seconds: int = 900) -> str:
    rows = _hosts_and_access(db)
    if not rows:
        return (
            "No coding agents have registered with this dashboard yet.\n"
            "A machine appears here after `csd-agent install` reports itself."
        )

    out = [f"REGISTERED CODING AGENTS (as of {_now().isoformat(timespec='seconds')})", ""]
    for host_row, access_row in rows:
        state = _state(host_row, access_row)
        if host_row["disconnected_at"]:
            liveness = f"disconnected ({_age(host_row['disconnected_at'])})"
        elif _maybe_stale(host_row, stale_after_seconds):
            liveness = f"possibly offline, last report {_age(host_row['last_seen_at'])}"
        else:
            liveness = f"connected, last report {_age(host_row['last_seen_at'])}"

        out.append(f"{host_row['label']}  [{host_row['agent_type']}]  {liveness}")
        out.append(f"  access: {state or 'not requested'}")
        if access_row is not None and access_row["last_error"]:
            out.append(f"  last install attempt failed: {access_row['last_error']}")
        command = _ssh_line(host_row, access_row)
        if command:
            if state == "ready":
                out.append(f"  {command}")
                out.append("  full shell — run the coding agent the way its user would")
            else:
                out.append("  a key is on file but not usable yet; wait for the next heartbeat")
        elif state == "requested":
            out.append("  the user has not authorized it; ask them (Settings → Host access)")
        out.append("")
    return "\n".join(out).rstrip()


def _render_sessions(
    db: Database, *, host: str | None, limit: int, stale_after_seconds: int = 900
) -> str:
    sessions, _ = ss.list_sessions(
        db,
        status=SessionStatus.running,
        agent_type=None,
        limit=max(1, min(limit, 200)),
        offset=0,
        stale_after_seconds=stale_after_seconds,
    )
    if host:
        sessions = [s for s in sessions if (s.host or "") == host]
    if not sessions:
        scope = f" on {host}" if host else ""
        return f"No running sessions{scope} right now."

    out = [f"RUNNING SESSIONS (as of {_now().isoformat(timespec='seconds')})", ""]
    for s in sessions:
        where = s.host or "no host reported"
        parts = [f"{where}  [{s.agent_type}]  {s.title!r}"]
        detail = []
        if s.project_name:
            detail.append(f"project: {s.project_name}")
        if s.workspace:
            detail.append(f"workspace: {s.workspace}")
        detail.append(f"started {_age(s.started_at)}")
        if s.possibly_stale:
            detail.append("possibly offline")
        out.append("  ".join(parts))
        out.append("  " + " · ".join(detail))
    return "\n".join(out)


def write_registry_file(
    db: Database, workspace_file: Path | None, *, stale_after_seconds: int = 900
) -> Path | None:
    """Regenerate the file the agent may read, if it changed.

    Never raises: a host reporting itself must not fail because a workspace is read-only. The
    caller is a request handler, and the cost of a stale file is a stale sentence, not a broken
    dashboard. Compare-before-write because the trigger is every heartbeat, and an mtime that
    moved every five minutes would make the file look like it was saying something new.
    """
    if workspace_file is None:
        return None
    try:
        text = render_markdown(db, stale_after_seconds=stale_after_seconds)
        if workspace_file.exists() and workspace_file.read_text(encoding="utf-8") == text:
            return workspace_file
        workspace_file.parent.mkdir(parents=True, exist_ok=True)
        tmp = workspace_file.with_suffix(".md.tmp")
        tmp.write_text(text, encoding="utf-8")
        tmp.replace(workspace_file)
        return workspace_file
    except OSError as exc:
        logger.warning("could not write %s: %s", workspace_file, exc)
        return None


def main(argv: list[str] | None = None) -> int:
    """The tool's entry point, run by the Pi extension in the agent's process tree.

    Deliberately self-contained: `--db` is the only input, the connection is read-only, and the
    printed text is the tool result verbatim. Anything that fails prints a sentence the model
    can act on rather than a traceback it cannot.
    """
    # Pinned rather than inherited: the text carries em dashes, and on Windows a pipe defaults to
    # the locale code page *and* to CRLF, so the bytes would arrive at Pi as mojibake with stray
    # carriage returns — an output bug that looks like a rendering one, and only on some machines.
    try:
        sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    except (AttributeError, ValueError):  # pragma: no cover - not a TextIOWrapper
        pass

    parser = argparse.ArgumentParser(prog="hosts_view", add_help=True)
    parser.add_argument("--db", required=True, help="path to the dashboard's sqlite file")
    parser.add_argument("--action", default="hosts", choices=["hosts", "sessions"])
    parser.add_argument("--host", default=None, help="filter sessions to one host label")
    parser.add_argument("--limit", type=int, default=50)
    args = parser.parse_args(argv)

    try:
        db = Database.open_read_only(Path(args.db))
    except Exception as exc:  # sqlite3.Error, OSError — the model gets a sentence either way
        print(f"could not open the dashboard database at {args.db}: {exc}")
        return 0
    try:
        print(render_tool_text(db, action=args.action, host=args.host, limit=args.limit))
    except Exception as exc:
        print(f"could not read the registry: {exc}")
        return 0
    finally:
        db.close()
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through main()
    raise SystemExit(main())
